// Chrome oracle for mix-blend-mode (the blended group's composite in scene.hlsl, the backdrop copy the scene schedule
// takes for it, and the isolated groups of stacking contexts): over a backdrop of a gradient and a dark and a light
// band (the cell's own background and boxes), boxes with a border, padding, a background and a child that overflows
// them, blended by every mode, with opacity, a translucent background, corner radii, a rotation, a mask, a clip-path
// and a blended child; and wrappers that isolate (isolation, opacity, z-index, a transform) or do not. Writes to
// tests/fixtures/mix_blend_mode the page's script (page.js, which builds the cases in #root), the cases' places
// (cases.json) and a screenshot of the page at device scale 1 (chrome.png), which tests/mix_blend_mode_metal_tests.mm
// compares a View's drawing with.
//
//   node tools/browser_mix_blend_mode_reference.mjs [chrome executable]
import {spawn} from 'node:child_process';
import {createServer} from 'node:http';
import {existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const repo = resolve(fileURLToPath(new URL('..', import.meta.url)));
const directory = resolve(repo, 'tests/fixtures/mix_blend_mode');
const defaults = ['C:/Program Files/Google/Chrome/Application/chrome.exe',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'];
const executable = process.argv[2] ?? defaults.find(existsSync);
if (!executable || !existsSync(executable)) throw new Error('Provide a local Chromium executable as the first argument');
mkdirSync(directory, {recursive: true});

// Each case: a cell of 170 px whose background is a gradient, with a dark and a light band across it (its children,
// drawn first), then a box of 100 x 100 px content, 8 px padding, a 6 px border (128 px border box) at 20, 20, a child
// that overflows it at its bottom right, with its blend mode (and more style), inside a wrapper of more style when the
// case has one.
const cell = 170;
const box = 'position:absolute;box-sizing:content-box;left:20px;top:20px;width:100px;height:100px;padding:8px;' +
  'border:6px solid #f59e0b;background:#3b82f6;';
const modes = ['normal', 'multiply', 'screen', 'overlay', 'darken', 'lighten', 'color-dodge', 'color-burn', 'hard-light',
  'soft-light', 'difference', 'exclusion', 'hue', 'saturation', 'color', 'luminosity', 'plus-lighter'];
const cases = [
  ...modes.map((m) => [m, 'mix-blend-mode:' + m]),
  ['multiply opacity', 'mix-blend-mode:multiply;opacity:.6'],
  ['multiply translucent', 'mix-blend-mode:multiply;background:rgba(59,130,246,.5)'],
  ['difference rounded', 'mix-blend-mode:difference;border-radius:30px'],
  ['screen rotated', 'mix-blend-mode:screen;transform:rotate(12deg)'],
  ['multiply masked', 'mix-blend-mode:multiply;mask-image:linear-gradient(to bottom, #000, transparent)'],
  ['multiply clipped', 'mix-blend-mode:multiply;clip-path:circle(50%)'],
  ['nested blend', 'mix-blend-mode:multiply', 'mix-blend-mode:difference'],
  ['isolation isolate', 'mix-blend-mode:difference', null, 'isolation:isolate'],
  ['opacity wrapper', 'mix-blend-mode:difference', null, 'opacity:.99'],
  ['z-index wrapper', 'mix-blend-mode:difference', null, 'position:relative;z-index:0'],
  ['transform wrapper', 'mix-blend-mode:difference', null, 'transform:translateX(0)'],
  ['plain wrapper', 'mix-blend-mode:difference', null, 'position:relative'],
].map(([name, style, child = null, wrapper = null], i) =>
  ({name, style, child, wrapper, rect: [(i % 5) * cell, Math.floor(i / 5) * cell, cell, cell]}));
const width = 5 * cell;
const height = Math.ceil(cases.length / 5) * cell;
writeFileSync(resolve(directory, 'cases.json'), JSON.stringify({width, height, cases}, null, 1) + '\n');
writeFileSync(resolve(directory, 'page.js'), `// Generated by tools/browser_mix_blend_mode_reference.mjs: the cases of cases.json in #root.
const cases = ${JSON.stringify(cases.map((c) => [c.rect[0], c.rect[1], c.style, c.child, c.wrapper]))};
const box = ${JSON.stringify(box)};
const root = document.getElementById('root');
const make = (parent, style) => {
  const e = document.createElement('div');
  e.setAttribute('style', style);
  parent.appendChild(e);
  return e;
};
cases.forEach(([left, top, style, child, wrapper], i) => {
  const host = make(root, 'position:absolute;left:' + left + 'px;top:' + top + 'px;width:${cell}px;height:${cell}px;' +
    'background:linear-gradient(90deg, #ff6b6b, #4ecdc4 50%, #ffe66d)');
  make(host, 'position:absolute;left:0;top:50px;width:${cell}px;height:24px;background:#1f2937');
  make(host, 'position:absolute;left:0;top:100px;width:${cell}px;height:24px;background:#f9fafb');
  const parent = wrapper ? make(host, wrapper) : host;
  const e = make(parent, box + style);
  make(e, 'position:absolute;left:80px;top:80px;width:64px;height:64px;background:#ef4444;' + (child ?? ''));
});
`);

const page = '<!doctype html><html><head><meta charset=utf-8><style>html,body{margin:0;background:#ffffff}' +
  '#root{position:relative}</style></head><body><div id=root></div><script src=page.js></script></body></html>';
const files = {'page.html': Buffer.from(page), 'page.js': readFileSync(resolve(directory, 'page.js'))};
const server = createServer((request, response) => {
  const name = decodeURIComponent(new URL(request.url, 'http://localhost').pathname.slice(1));
  const body = files[name];
  if (!body) {
    response.writeHead(404);
    response.end();
    return;
  }
  response.writeHead(200, {'content-type': name.endsWith('.html') ? 'text/html' : 'text/javascript'});
  response.end(body);
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const origin = `http://127.0.0.1:${server.address().port}/`;

const profile = mkdtempSync(join(tmpdir(), 'weft-mix-blend-mode-'));
const child = spawn(executable, ['--headless=new', '--no-first-run', '--disable-background-networking',
  '--remote-debugging-port=0', '--force-device-scale-factor=1', '--force-color-profile=srgb',
  `--window-size=${width},${height}`, '--user-data-dir=' + profile, 'about:blank'],
{windowsHide: true, stdio: ['ignore', 'ignore', 'pipe']});
let socket;
try {
  const endpoint = await new Promise((resolveEndpoint, reject) => {
    let text = '';
    const limit = setTimeout(() => reject(new Error('Chromium startup timeout')), 20000);
    child.on('error', reject);
    child.stderr.on('data', (c) => {
      text += c;
      const m = text.match(/DevTools listening on ws:\/\/127\.0\.0\.1:(\d+)\//);
      if (m) {
        clearTimeout(limit);
        resolveEndpoint('http://127.0.0.1:' + m[1]);
      }
    });
  });
  const version = await (await fetch(endpoint + '/json/version')).json();
  const tab = (await (await fetch(endpoint + '/json/list')).json()).find((t) => t.type === 'page');
  socket = new WebSocket(tab.webSocketDebuggerUrl);
  await new Promise((r, j) => {
    socket.addEventListener('open', r, {once: true});
    socket.addEventListener('error', j, {once: true});
  });
  let next = 0;
  const pending = new Map();
  const loaded = [];
  socket.addEventListener('message', (event) => {
    const message = JSON.parse(event.data);
    if (message.id && pending.has(message.id)) {
      const {resolve: done, reject} = pending.get(message.id);
      pending.delete(message.id);
      message.error ? reject(new Error(message.error.message)) : done(message.result);
    } else if (message.method === 'Page.loadEventFired') {
      loaded.shift()?.();
    }
  });
  const call = (method, params = {}) => new Promise((done, reject) => {
    const id = ++next;
    pending.set(id, {resolve: done, reject});
    socket.send(JSON.stringify({id, method, params}));
  });
  await call('Page.enable');
  await call('Emulation.setDeviceMetricsOverride', {width, height, deviceScaleFactor: 1, mobile: false});
  const ready = new Promise((r) => loaded.push(r));
  await call('Page.navigate', {url: origin + 'page.html'});
  await ready;
  await call('Runtime.evaluate', {expression: 'new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)))',
    awaitPromise: true});
  const shot = await call('Page.captureScreenshot', {format: 'png', clip: {x: 0, y: 0, width, height, scale: 1}});
  writeFileSync(resolve(directory, 'chrome.png'), Buffer.from(shot.data, 'base64'));
  writeFileSync(resolve(directory, 'browser.txt'), version.Browser + '\n');
  console.log(`Recorded ${cases.length} cases from ${version.Browser} to ${directory}`);
} finally {
  socket?.close();
  server.close();
  const exited = new Promise((r) => child.once('exit', r));
  child.kill();
  await exited;
  rmSync(profile, {recursive: true, force: true, maxRetries: 5, retryDelay: 200});
}
