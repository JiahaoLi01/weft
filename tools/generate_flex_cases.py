"""Generate checked-in C++ fixture inputs; browser reads the same JSON via JS."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]


def node(value):
    quote = lambda s: json.dumps(s, ensure_ascii=True)
    style = ','.join('{' + quote(k) + ',' + quote(v) + '}' for k, v in sorted(value.get('style', {}).items()))
    children = ','.join(node(child) for child in value.get('children', []))
    return '{' + quote(value['id']) + ',{' + style + '},' + quote(value.get('text', '')) + ',{' + children + '}}'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = ROOT / 'tests/fixtures/flex_layout_cases.json'
    raw = source.read_bytes()
    data = json.loads(raw)
    cases = ',\n'.join('{' + json.dumps(c['id']) + ',' + node(c['root']) + '}' for c in data['cases'])
    header = ('// Generated by tools/generate_flex_cases.py; edit the JSON input.\n'
              '#pragma once\n#include "caseelephant/flex_probe.hpp"\n'
              'namespace caseelephant::fixtures {\n'
              'struct Case { std::string id; FlexProbeNode root; };\n'
              'inline std::vector<Case> flex_cases() { return {\n' + cases + '\n}; }\n'
              'inline constexpr const char* input_sha256 = "' + hashlib.sha256(raw).hexdigest() + '";\n}\n')
    browser_data = dict(data, input_sha256=hashlib.sha256(raw).hexdigest())
    browser = 'globalThis.caseElephantFlexFixture = ' + json.dumps(browser_data, ensure_ascii=False, indent=2) + ';\n'
    for filename, content in [('flex_layout_cases.hpp', header), ('flex_layout_cases.js', browser)]:
        destination = source.parent / filename
        if args.check:
            if destination.read_text(encoding='utf-8') != content:
                raise SystemExit('Generated fixture out of date: ' + filename)
        else:
            destination.write_text(content, encoding='utf-8', newline='\n')
    print(f'{len(data["cases"])} shared Flex cases; generated inputs verified' if args.check else f'Generated {len(data["cases"])} shared Flex cases')


if __name__ == '__main__':
    main()
