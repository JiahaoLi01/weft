// Chrome oracle for CSS clip-path (src/scene/scene_clip_path.cpp's shapes, the clip chain of scene.hlsl and the hit
// test's clips): boxes with a border, padding, a background and a child that overflows them, each clipped by a shape
// (inset, circle, ellipse, polygon, path, rect, xywh) of a reference box, or by a reference box alone, with corner radii,
// shadows, transforms, opacity, nesting and overflow clips. Writes to tests/fixtures/clip_path the page's script
// (page.js, which builds the cases in #root), the cases' places (cases.json), a screenshot of the page at device scale 1
// (chrome.png) and, for points over every case, which element a press there reaches (hits.json): what
// tests/clip_path_metal_tests.mm compares a View's drawing and hits with.
//
//   node tools/browser_clip_path_reference.mjs [chrome executable]
import {spawn} from 'node:child_process';
import {createServer} from 'node:http';
import {existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const repo = resolve(fileURLToPath(new URL('..', import.meta.url)));
const directory = resolve(repo, 'tests/fixtures/clip_path');
const defaults = ['C:/Program Files/Google/Chrome/Application/chrome.exe',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'];
const executable = process.argv[2] ?? defaults.find(existsSync);
if (!executable || !existsSync(executable)) throw new Error('Provide a local Chromium executable as the first argument');
mkdirSync(directory, {recursive: true});

// Each case: a box of 100 x 100 px content, 8 px padding, a 6 px border (128 px border box) at the top left of a cell,
// a child that overflows it at its bottom right, and its clip-path (with more style). Cells are 170 px apart.
const cell = 170;
const box = 'position:absolute;box-sizing:content-box;width:100px;height:100px;padding:8px;border:6px solid #f59e0b;' +
  'background:#3b82f6;';
const cases = [
  ['none', 'none'],
  ['inset', 'inset(10px)'],
  ['inset percentages', 'inset(10% 20% 15% 5%)'],
  ['inset round', 'inset(10px round 20px)'],
  ['inset elliptical corners', 'inset(5px 10px 15px 20px round 10px 0 30px 5px / 5px 20px)'],
  ['circle', 'circle()'],
  ['circle percentage', 'circle(40%)'],
  ['circle at', 'circle(50px at 30% 40%)'],
  ['circle farthest-side', 'circle(farthest-side at 20% 20%)'],
  ['ellipse', 'ellipse()'],
  ['ellipse at', 'ellipse(40% 30% at 60% 50%)'],
  ['ellipse sides', 'ellipse(closest-side farthest-side at 30% 50%)'],
  ['polygon diamond', 'polygon(50% 0, 100% 50%, 50% 100%, 0 50%)'],
  ['polygon triangle', 'polygon(0 0, 100% 0, 50% 100%)'],
  ['polygon star nonzero', 'polygon(50% 0, 79% 90%, 2% 35%, 98% 35%, 21% 90%)'],
  ['polygon star evenodd', 'polygon(evenodd, 50% 0, 79% 90%, 2% 35%, 98% 35%, 21% 90%)'],
  ['path triangle', "path('M 0 0 L 128 0 L 64 128 Z')"],
  ['path curves', "path('M 64 0 C 128 0 128 128 64 128 C 0 128 0 0 64 0 Z')"],
  ['path evenodd hole', "path(evenodd, 'M 0 0 H 128 V 128 H 0 Z M 32 32 H 96 V 96 H 32 Z')"],
  ['path arcs', "path('M 10 64 A 54 54 0 0 1 118 64 L 64 120 Z')"],
  ['circle content-box', 'circle(50%) content-box'],
  ['inset padding-box', 'inset(0) padding-box'],
  ['circle margin-box', 'circle(50%) margin-box', 'margin:10px;'],
  ['padding-box rounded', 'padding-box', 'border-radius:30px;'],
  ['border-box rounded', 'border-box', 'border-radius:20px 40px;'],
  ['rounded polygon', 'polygon(0 0, 100% 0, 100% 100%, 30% 70%)', 'border-radius:30px;'],
  ['shadow', 'inset(0)', 'box-shadow:0 0 0 10px #10b981;'],
  ['rotated', 'polygon(50% 0, 100% 100%, 0 100%)', 'transform:rotate(20deg);'],
  ['opacity', 'circle(45%)', 'opacity:0.6;'],
  ['rect', 'rect(10px 90% 80% 10px round 6px)'],
  ['xywh', 'xywh(10px 15px 70% 60% round 8px)'],
  ['webkit prefix', 'circle(45%)', '', '-webkit-clip-path'],
  ['nested', 'inset(10px round 30px)', '', 'clip-path', 'polygon(0 0, 100% 0, 0 100%)'],
  ['inside overflow', 'circle(60%)', '', 'clip-path', null, 'overflow:hidden;border-radius:24px;'],
].map(([name, value, style = '', property = 'clip-path', child = null, parent = null], i) =>
  ({name, value, style, property, child, parent, rect: [(i % 5) * cell, Math.floor(i / 5) * cell, cell, cell]}));
const width = 5 * cell;
const height = Math.ceil(cases.length / 5) * cell;
// Points to press in each cell: a 7 x 7 grid over it, off the grid of the shapes' round numbers.
const offsets = [7, 29, 51, 73, 97, 119, 141];
const points = cases.flatMap((c, i) => offsets.flatMap((y) => offsets.map((x) => [i, c.rect[0] + x + 0.5, c.rect[1] + y + 0.5])));
writeFileSync(resolve(directory, 'cases.json'), JSON.stringify({width, height, cases, points}, null, 1) + '\n');
writeFileSync(resolve(directory, 'page.js'), `// Generated by tools/browser_clip_path_reference.mjs: the cases of cases.json in #root. A press logs the id of the
// element it reaches in window.__hits.
const cases = ${JSON.stringify(cases.map((c) => [c.rect[0], c.rect[1], c.value, c.style, c.property, c.child, c.parent]))};
const box = ${JSON.stringify(box)};
const root = document.getElementById('root');
cases.forEach(([left, top, value, style, property, child, parent], i) => {
  const host = document.createElement('div');
  host.setAttribute('style', 'position:absolute;left:' + left + 'px;top:' + top + 'px;width:${cell}px;height:${cell}px;' +
    (parent ?? ''));
  host.id = 'cell' + i;
  const e = document.createElement('div');
  e.id = 'case' + i;
  e.setAttribute('style', box + 'left:0;top:0;' + style + property + ':' + value);
  const inner = document.createElement('div');
  inner.id = 'child' + i;
  inner.setAttribute('style', 'position:absolute;left:80px;top:80px;width:64px;height:64px;background:#ef4444;' +
    (child ? 'clip-path:' + child : ''));
  e.appendChild(inner);
  host.appendChild(e);
  root.appendChild(host);
});
window.__hits = [];
document.addEventListener('mousedown', (event) => window.__hits.push(event.target.id || event.target.tagName));
`);

const page = '<!doctype html><html><head><meta charset=utf-8><style>html,body{margin:0;background:#ffffff}' +
  '#root{position:relative}</style></head><body><div id=root></div><script src=page.js></script></body></html>';
const files = {'page.html': Buffer.from(page), 'page.js': readFileSync(resolve(directory, 'page.js'))};
const server = createServer((request, response) => {
  const name = decodeURIComponent(new URL(request.url, 'http://localhost').pathname.slice(1));
  const body = files[name];
  if (!body) {
    response.writeHead(404);
    response.end();
    return;
  }
  response.writeHead(200, {'content-type': name.endsWith('.html') ? 'text/html' : 'text/javascript'});
  response.end(body);
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const origin = `http://127.0.0.1:${server.address().port}/`;

const profile = mkdtempSync(join(tmpdir(), 'weft-clip-path-'));
const child = spawn(executable, ['--headless=new', '--no-first-run', '--disable-background-networking',
  '--remote-debugging-port=0', '--force-device-scale-factor=1', '--force-color-profile=srgb',
  `--window-size=${width},${height}`, '--user-data-dir=' + profile, 'about:blank'],
{windowsHide: true, stdio: ['ignore', 'ignore', 'pipe']});
let socket;
try {
  const endpoint = await new Promise((resolveEndpoint, reject) => {
    let text = '';
    const limit = setTimeout(() => reject(new Error('Chromium startup timeout')), 20000);
    child.on('error', reject);
    child.stderr.on('data', (c) => {
      text += c;
      const m = text.match(/DevTools listening on ws:\/\/127\.0\.0\.1:(\d+)\//);
      if (m) {
        clearTimeout(limit);
        resolveEndpoint('http://127.0.0.1:' + m[1]);
      }
    });
  });
  const version = await (await fetch(endpoint + '/json/version')).json();
  const tab = (await (await fetch(endpoint + '/json/list')).json()).find((t) => t.type === 'page');
  socket = new WebSocket(tab.webSocketDebuggerUrl);
  await new Promise((r, j) => {
    socket.addEventListener('open', r, {once: true});
    socket.addEventListener('error', j, {once: true});
  });
  let next = 0;
  const pending = new Map();
  const loaded = [];
  socket.addEventListener('message', (event) => {
    const message = JSON.parse(event.data);
    if (message.id && pending.has(message.id)) {
      const {resolve: done, reject} = pending.get(message.id);
      pending.delete(message.id);
      message.error ? reject(new Error(message.error.message)) : done(message.result);
    } else if (message.method === 'Page.loadEventFired') {
      loaded.shift()?.();
    }
  });
  const call = (method, params = {}) => new Promise((done, reject) => {
    const id = ++next;
    pending.set(id, {resolve: done, reject});
    socket.send(JSON.stringify({id, method, params}));
  });
  await call('Page.enable');
  await call('Emulation.setDeviceMetricsOverride', {width, height, deviceScaleFactor: 1, mobile: false});
  const ready = new Promise((r) => loaded.push(r));
  await call('Page.navigate', {url: origin + 'page.html'});
  await ready;
  await call('Runtime.evaluate', {expression: 'new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)))',
    awaitPromise: true});
  const shot = await call('Page.captureScreenshot', {format: 'png', clip: {x: 0, y: 0, width, height, scale: 1}});
  writeFileSync(resolve(directory, 'chrome.png'), Buffer.from(shot.data, 'base64'));
  for (const [, x, y] of points) {
    await call('Input.dispatchMouseEvent', {type: 'mousePressed', x, y, button: 'left', buttons: 1, clickCount: 1});
    await call('Input.dispatchMouseEvent', {type: 'mouseReleased', x, y, button: 'left', buttons: 0, clickCount: 1});
  }
  const hits = (await call('Runtime.evaluate', {expression: 'JSON.stringify(window.__hits)', returnByValue: true}))
    .result.value;
  writeFileSync(resolve(directory, 'hits.json'), JSON.stringify({browser: version.Browser, hits: JSON.parse(hits)}) +
    '\n');
  console.log(`Recorded ${cases.length} cases and ${points.length} presses from ${version.Browser} to ${directory}`);
} finally {
  socket?.close();
  server.close();
  const exited = new Promise((r) => child.once('exit', r));
  child.kill();
  await exited;
  rmSync(profile, {recursive: true, force: true, maxRetries: 5, retryDelay: 200});
}
